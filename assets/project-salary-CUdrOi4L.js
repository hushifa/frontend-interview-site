<p>先了解市场范围。可以参考招聘网站上同城市、同级别岗位标注的薪资，问问在类似公司工作的朋友，或者看行业的薪资报告。MDN 的 Finding a job 也建议提前了解目标岗位在对应级别和地区的常见薪资范围，以及健康保险、奖金这类其他福利，这在决定是否接受 offer 时会有用。</p>
