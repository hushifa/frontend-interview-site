<p>优化后的代码是按反馈猜出来的，所以必须能退回去。V8 在可能失败的检查点上保存了解释器的状态信息，检查失败时，去优化器用这些信息重建解释器的栈帧，让函数在 Ignition 里接着执行，结果不会出错，只是慢了。</p>
