<p>团队的长期加班，很多时候不是因为工作量本身，而是因为需求中途不断增加、估时不准、风险发现得太晚。MDN 的 Workflows and processes 在介绍敏捷开发时也提到，这种方式更容易出现范围蔓延（项目进行中不断加需求）和交付延期，而且会有持续的交付节奏和压力。</p>
